-- Phase 1 foundation schema: schema_meta + idempotency scaffolding.
-- Domain tables (users, products, orders, ...) are added in later phases.
-- Flyway executes each version once, so seed inserts need no upsert.

CREATE TABLE schema_meta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_key      VARCHAR(100) NOT NULL,
    schema_value    VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_schema_meta_key UNIQUE (schema_key)
);

INSERT INTO schema_meta (schema_key, schema_value) VALUES ('platform.phase', '1-foundation');
INSERT INTO schema_meta (schema_key, schema_value) VALUES ('platform.version', '0.1.0');

CREATE TABLE processed_events (
    id              UUID PRIMARY KEY,
    consumer_name   VARCHAR(150) NOT NULL,
    event_id        VARCHAR(200) NOT NULL,
    processed_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_processed_events_consumer_event UNIQUE (consumer_name, event_id)
);

CREATE INDEX idx_processed_events_processed_at ON processed_events (processed_at);
